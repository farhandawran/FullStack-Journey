        "from collections import deque\n",
        "import time\n",
        "\n",
        "GOAL = (1, 2, 3,\n",
        "        4, 5, 6,\n",
        "        7, 8, 0)          # 0 represents the blank tile\n",
        "\n",
        "MOVES = {'Up': -3, 'Down': 3, 'Left': -1, 'Right': 1}\n",
        "\n",
        "def actions(state):\n",
        "    \"\"\"Return the legal moves of the blank tile.\"\"\"\n",
        "    i = state.index(0)\n",
        "    row, col = divmod(i, 3)\n",
        "    legal = []\n",
        "    if row > 0: legal.append('Up')\n",
        "    if row < 2: legal.append('Down')\n",
        "    if col > 0: legal.append('Left')\n",
        "    if col < 2: legal.append('Right')\n",
        "    return legal\n",
        "\n",
        "def result(state, action):\n",
        "    \"\"\"Transition model: swap the blank with the neighbouring tile.\"\"\"\n",
        "    i = state.index(0)\n",
        "    j = i + MOVES[action]\n",
        "    s = list(state)\n",
        "    s[i], s[j] = s[j], s[i]\n",
        "    return tuple(s)\n",
        "\n",
        "def goal_test(state):\n",
        "    return state == GOAL\n",
        "\n",
        "def is_solvable(state):\n",
        "    tiles = [t for t in state if t != 0]\n",
        "    inversions = sum(1 for a in range(len(tiles))\n",
        "                       for b in range(a + 1, len(tiles)) if tiles[a] > tiles[b])\n",
        "    return inversions % 2 == 0\n",
        "\n",
        "def solve_bfs(start):\n",
        "    frontier = deque([(start, [])])\n",
        "    explored = {start}\n",
        "    expanded = 0\n",
        "    while frontier:\n",
        "        state, path = frontier.popleft()\n",
        "        if goal_test(state):\n",
        "            return path, expanded, len(explored)\n",
        "        expanded += 1\n",
        "        for a in actions(state):\n",
        "            child = result(state, a)\n",
        "            if child not in explored:\n",
        "                explored.add(child)\n",
        "                frontier.append((child, path + [a]))\n",
        "    return None, expanded, len(explored)\n",
        "\n",
        "def show(state):\n",
        "    for r in range(3):\n",
        "        print(' '.join(str(x) if x else '_' for x in state[r*3:r*3+3]))\n",
        "\n",
        "start = (8, 1, 3,\n",
        "         4, 0, 2,\n",
        "         7, 6, 5)\n",
        "print(\"Start state:\"); show(start)\n",
        "print(\"Solvable:\", is_solvable(start))\n",
        "t0 = time.perf_counter()\n",
        "path, expanded, generated = solve_bfs(start)\n",
        "t1 = time.perf_counter()\n",
        "print(\"Solution :\", path)\n",
        "print(\"Moves    :\", len(path))\n",
        "print(\"Nodes expanded :\", expanded)\n",
        "print(\"Nodes generated:\", generated)\n",
        "print(f\"Time taken     : {(t1-t0)*1000:.2f} ms\")\n",
        "def print_solution(start, path):\n",
        "    \"\"\"Print the board after every move of the solution.\"\"\"\n",
        "    state = start\n",
        "    print(\"Initial state:\")\n",
        "    show(state)\n",
        "    for step, action in enumerate(path, 1):\n",
        "        state = result(state, action)\n",
        "        print(f\"\\nStep {step}: Move blank {action}\")\n",
        "        show(state)\n",
        "\n",
        "start = (8, 1, 3,\n",
        "         4, 0, 2,\n",
        "         7, 6, 5)\n",
        "\n",
        "print(\"Start state:\")\n",
        "show(start)\n",
        "print(\"Solvable:\", is_solvable(start))\n",
        "\n",
        "t0 = time.perf_counter()\n",
        "path, expanded, generated = solve_bfs(start)\n",
        "t1 = time.perf_counter()\n",
        "\n",
        "print(\"Solution :\", path)\n",
        "print(\"Moves    :\", len(path))\n",
        "print(\"Nodes expanded :\", expanded)\n",
        "print(\"Nodes generated:\", generated)\n",
        "print(f\"Time taken     : {(t1-t0)*1000:.2f} ms\")\n",
        "\n",
        "print(\"\\n--- Step-by-step solution ---\")\n",
        "print_solution(start, path)\n",
        "print(\"Final state:\"); show(GOAL)"
